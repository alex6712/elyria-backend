class ProfileNotFoundError(Exception):
    """Профиль не найден.

    Возникает при попытке обращения к профилю, отсутствующему
    для указанной учётной записи.
    """

    pass


class IdentityNotFoundError(Exception):
    """Учётная запись не найдена.

    Возникает при попытке обращения к учётной записи, отсутствующей
    в системе, несмотря на предъявление действительного access-токена
    (например, если учётная запись была удалена после выпуска токена).
    """

    pass


class NothingToUpdateError(Exception):
    """Отсутствуют поля для обновления.

    Возникает, когда команда изменения профиля не содержит ни одного
    обновляемого поля: все необязательные поля остались ``UNSET``.
    """

    pass


class SessionNotFoundError(Exception):
    """Сессия не найдена.

    Возникает при попытке обращения к несуществующей сессии
    пользователя.
    """

    pass


class IncorrectUsernameOrPasswordError(Exception):
    """Исключение при ошибке обработки запроса логина.

    Notes
    -----
    Используется для обработки случаев, когда не получилось
    аутентифицировать пользователя по предоставленным учётным данным.
    """

    pass


class IncorrectCurrentPasswordError(Exception):
    """Неверный текущий пароль.

    Возникает при попытке смены пароля, если переданный текущий
    пароль не совпадает с сохранённым хэшем пароля учётной записи.
    """

    pass


class NewPasswordSameAsOldError(Exception):
    """Новый пароль совпадает со старым.

    Возникает при попытке смены пароля, если новый пароль совпадает
    с текущим сохранённым паролем учётной записи.
    """

    pass


class CompromisedPasswordError(Exception):
    """Скомпрометированный пароль.

    Возникает при попытке регистрации пользователя с паролем,
    который встречается в известных утечках данных. Исключение
    не раскрывает деталей проверки, чтобы не помогать злоумышленнику
    в оценке выбранных им паролей.
    """

    pass
