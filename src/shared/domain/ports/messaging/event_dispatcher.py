from collections.abc import Awaitable, Callable
from typing import Any, Protocol


class EventDispatcher(Protocol):
    """Порт диспетчеризации событий для реализации паттерна Publish/Subscribe.

    Определяет контракт, который должна реализовать инфраструктура
    для публикации и обработки доменных событий внутри приложения.
    Позволяет разделять логику генерации событий (доменный слой)
    и их обработку (прикладной/инфраструктурный слой), сохраняя
    слабую связность компонентов.

    В монолитном приложении реализация этого порта может работать
    как in-memory шина событий в пределах одного процесса либо
    делегировать отправку во внешнюю шину (RabbitMQ, Kafka и т. п.).
    """

    async def subscribe[T](
        self, event_type: type[T], handler: Callable[[T], Awaitable[None]]
    ) -> None:
        """Подписаться на события заданного типа.

        Регистрирует асинхронный обработчик для событий указанного
        доменного типа. После регистрации все события этого типа,
        отправленные через метод ``publish``, будут переданы
        подписанному обработчику.

        Parameters
        ----------
        event_type : type[T]
            Тип доменного события, на которое регистрируется подписка.
            Должен быть конкретным классом события.
        handler : Callable[[T], Awaitable[None]]
            Асинхронная функция-обработчик, принимающая событие типа ``T``
            и не возвращающая значимого результата.

        Notes
        -----
        - Один и тот же тип события может иметь несколько подписчиков.
        - Порядок вызова обработчиков не гарантируется.
        """

    async def publish(self, event: Any) -> None:
        """Опубликовать событие в шине событий.

        Отправляет переданное событие всем зарегистрированным подписчикам,
        чьи типы событий соответствуют типу переданного объекта.
        Если для данного типа события нет подписчиков, событие игнорируется.

        Метод не блокирует выполнение до завершения всех обработчиков,
        если реализация явно не гарантирует синхронную обработку.

        Parameters
        ----------
        event : Any
            Экземпляр доменного события для публикации.
        """
