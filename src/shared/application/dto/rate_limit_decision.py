from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class RateLimitDecision:
    """Результат проверки ограничения частоты запросов.

    Неизменяемый объект, содержащий вердикт ограничителя и
    сопутствующие счётчики, необходимые для формирования
    полного ответа.

    Решение содержит счётчики независимо от вердикта: при
    положительном решении они передаются в HTTP-ответ, при
    отрицательном - в исключение и далее в ответ об ошибке.
    Дальнейшая судьба счётчиков определяется сценарием
    приложения, а не ограничителем.

    Attributes
    ----------
    allowed : bool
        ``True``, если запрос укладывается в лимит и может быть
        обработан. ``False``, если лимит исчерпан.
    limit : int
        Максимальное количество запросов, разрешённое в текущем
        окне ограничения.
    remaining : int
        Количество запросов, доступных после учёта текущего.
        Значение ``0`` означает, что лимит исчерпан.
    retry_after : int
        Количество секунд, по прошествии которого счётчик текущего
        окна будет сброшен и запрос снова станет доступным.
        Заполняется только при превышении лимита, для разрешённого
        запроса равно нулю.
    reset_after : int
        Количество секунд до полного сброса окна ограничения.
    """

    allowed: bool
    limit: int
    remaining: int
    retry_after: int
    reset_after: int
